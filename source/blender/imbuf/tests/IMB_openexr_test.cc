TEST_F(imbuf_openexr, decode_pixel)
{
  ImFileColorSpace colorspace;
  ImBuf *image = imb_load_openexr(exr_pixel, sizeof(exr_pixel), 0, colorspace);
  ASSERT_NE(image, nullptr);
  EXPECT_EQ(image->x, 1);
  EXPECT_EQ(image->y, 1);
  EXPECT_FLOAT_EQ(image->float_buffer.data[0], 0.25f);
  EXPECT_FLOAT_EQ(image->float_buffer.data[1], 0.5f);
  EXPECT_FLOAT_EQ(image->float_buffer.data[2], 0.75f);
  EXPECT_FLOAT_EQ(image->float_buffer.data[3], 1.0f);
  IMB_freeImBuf(image);
}

TEST_F(imbuf_openexr, pixel_allocation_failure)
{
  using namespace mem_guarded::internal;
  struct RestoreAllocator {
    decltype(mem_mallocN) original = mem_mallocN;
    ~RestoreAllocator() { mem_mallocN = original; }
  } restore;
  static auto original = mem_mallocN;
  static bool failed;
  failed = false;
  mem_mallocN = [](size_t size, const char *name) -> void * {
    if (size == sizeof(float) * 4 && std::strcmp(name, "imb_alloc_buffer") == 0) {
      failed = true;
      return nullptr;
    }
    return original(size, name);
  };
  ImFileColorSpace colorspace;
  ImBuf *image = imb_load_openexr(exr_pixel, sizeof(exr_pixel), 0, colorspace);
  EXPECT_TRUE(failed);
  EXPECT_EQ(image, nullptr);
  if (image) {
    IMB_freeImBuf(image);
  }
}

